// INTEGRATION LAYER — API halisi ya backend (Kubadilishana / EssTransfer)
//
// Ramani ya data (GET /feedback/admin/all):
//   feedback item → mazungumzo moja kwa MTU (RULE 1):
//     key (userId) = user_phone (au user_id kama simu haipo)
//     jina  = user_name (au user_phone kama jina hakipo)
//     msg ya mtumiaji = "subject\nmessage"  @created_at
//     msg ya admin    = admin_reply          @admin_replied_at
//                       + quote ya ujumbe wa mtumiaji (kama WhatsApp)
//
//   sendReply  → POST /feedback/admin/{id}/reply
//                (id = feedback ya ujumbe unaojibu; bila quote = ile isiyojibiwa
//                 ya mwisho ya mtumiaji huyo)
//   delete     → DELETE /feedback/admin/{id} kwa kila feedback ya mtumiaji huyo
//   LIVE       → WS 'notification' (feedback.new / feedback.replied) + timer 30s
//
//  CLIENTID ECHO: backend ya sasa hairudishi clientId. Repository hii
//  ina-"fake echo": jibu lililohifadhiwa linalinganishwa na copy ya local
//  kwa (userId + maandishi + muda), kisha clientId inabandikwa — hivyo
//  ChatController inaondoa copy ya local NA UJUMBE HAIONEKANI MARA MBILI.
// ============================================================================

DateTime _parseIso(dynamic iso, [DateTime? fallback]) {
  final s = iso?.toString() ?? '';
  if (s.isEmpty) return fallback ?? DateTime.now();
  try {
    return DateTime.parse(s).toLocal();
  } catch (_) {
    return fallback ?? DateTime.now();
  }
}

/// Jina la mtu kwenye orodha (jina halisi, la simu kama hakijulikani).
String _displayName(Map<String, dynamic> m) {
  final name = (m['user_name'] ?? m['full_name'] ?? '').toString().trim();
  if (name.isNotEmpty && !name.startsWith('+')) return name;
  final p = (m['user_phone'] ?? m['phone'] ?? '').toString().trim();
  return p.isNotEmpty ? p : 'Mtumiaji';
}

/// Ujumbe wa mtumiaji: subject + message (kama zipo zote mbili).
String _userText(Map<String, dynamic> m) {
  final subject = (m['subject'] ?? '').toString().trim();
  final message = (m['message'] ?? '').toString().trim();
  return [
    if (subject.isNotEmpty) subject,
    if (message.isNotEmpty) message,
  ].join('\n');
}

/// Jibu la admin: admin_reply (au reply kama ni String/Map yenye text).
String _replyText(Map<String, dynamic> m) {
  final a = (m['admin_reply'] ?? '').toString().trim();
  if (a.isNotEmpty) return a;
  final r = m['reply'];
  if (r is Map) {
    final rm = Map<String, dynamic>.from(r);
    return (rm['text'] ?? rm['message'] ?? '').toString().trim();
  }
  return (r ?? '').toString().trim();
}

/// Ufunguo wa mazungumzo (userId): simu ya mtumiaji, au id kama hakuna simu.
String _feedbackKey(Map<String, dynamic> m) {
  final p = (m['user_phone'] ?? m['phone'] ?? '').toString().trim();
  if (p.isNotEmpty) return p;
  return (m['user_id'] ?? m['_id'] ?? m['id'] ?? '').toString();
}

/// Jibu lililotumwa tukio la local — linasubiri kulinganishwa na server copy
/// (fake echo ya clientId, angalia maelezo hapo juu).
class _SentEcho {
  final String clientId;
  final String userId;
  final String text;
  final DateTime sentAt;
  bool matched = false;
  _SentEcho(this.clientId, this.userId, this.text, this.sentAt);
}

class ApiMaoniRepository implements MaoniRepository {
  ApiMaoniRepository._() {
    WebSocketService().on('notification', _onWs);
  }

  static final ApiMaoniRepository instance = ApiMaoniRepository._();

  List<Map<String, dynamic>> _items = const [];
  bool _loading = false;
  final _updates = StreamController<void>.broadcast();
  Timer? _timer;
  final List<_SentEcho> _sent = [];

  /// WS LIVE: maoni mpya / majibu mapya → refresh ya moja kwa moja.
  void _onWs(Map<String, dynamic> payload) {
    final type = (payload['type'] ?? payload['event'])?.toString() ?? '';
    if (type == 'feedback.new' || type == 'feedback.replied') refresh();
  }

  void _ensureTimer() {
    _timer ??= Timer.periodic(const Duration(seconds: 30), (_) => refresh());
  }

  /// LETA data mpya kutoka backend. Kimya kama imeshindikana (tunabakisha
  /// data ya zamani); matumizi ya kwanza huleta spinner kwenye inbox.
  Future<void> refresh({bool force = false}) async {
    if (!force && (_loading || !_updates.hasListener)) return;
    _loading = true;
    try {
      final res = await ApiService().adminListFeedback(status: '', q: '');
      final data = res.data;
      final list = data is List
          ? data
          : (data is Map
              ? (data['items'] as List? ?? data['results'] as List? ?? const [])
              : const []);
      _items = [
        for (final it in list)
          if (it is Map) Map<String, dynamic>.from(it),
      ];
      if (!_updates.isClosed) _updates.add(null);
    } catch (_) {
      // refresh ya nyuma ya pazia — data ya zamani inaendelea kuonekana
    } finally {
      _loading = false;
    }
  }

  // ---- Streams -------------------------------------------------------------

  @override
  Stream<List<Conversation>> watchConversations() async* {
    _ensureTimer();
    unawaited(refresh());
    yield _conversations();
    await for (final _ in _updates.stream) {
      yield _conversations();
    }
  }

  @override
  Stream<List<ChatMessage>> watchMessages(String userId) async* {
    _ensureTimer();
    unawaited(refresh());
    yield _messagesFor(userId);
    await for (final _ in _updates.stream) {
      yield _messagesFor(userId);
    }
  }

  // ---- Ramani: items → ChatMessage / Conversation ---------------------------

  List<ChatMessage> _messagesFor(String userId) {
    final out = <ChatMessage>[];
    final items = _items.where((m) => _feedbackKey(m) == userId).toList()
      ..sort((a, b) =>
          _parseIso(a['created_at']).compareTo(_parseIso(b['created_at'])));
    for (final m in items) {
      final id = (m['id'] ?? m['_id'] ?? '').toString();
      final created = _parseIso(m['created_at']);
      final userText = _userText(m);
      if (userText.isNotEmpty) {
        out.add(ChatMessage(
          id: '${id}u',
          userId: userId,
          fromAdmin: false,
          text: userText,
          time: created,
          status: MsgStatus.delivered,
        ));
      }
      final reply = _replyText(m);
      if (reply.isNotEmpty) {
        out.add(ChatMessage(
          id: '${id}r',
          userId: userId,
          fromAdmin: true,
          text: reply,
          time: _parseIso(m['admin_replied_at'] ?? m['replied_at'], created),
          status: MsgStatus.delivered,
          replyTo:
              userText.isEmpty ? null : ReplyRef('${id}u', _displayName(m), userText),
        ));
      }
    }
    _applyEchoes(out, userId);
    out.sort((a, b) => a.time.compareTo(b.time));
    return out;
  }

  /// Fake echo: jibu la server lenye maandishi sawa (na muda uleile) linapata
  /// clientId ya local — ChatController inaondoa copy ya local (RULE 2).
  void _applyEchoes(List<ChatMessage> msgs, String userId) {
    for (final e in _sent) {
      if (e.matched || e.userId != userId) continue;
      for (var i = msgs.length - 1; i >= 0; i--) {
        final m = msgs[i];
        final inWindow =
            !m.time.isBefore(e.sentAt.subtract(const Duration(minutes: 5)));
        if (m.fromAdmin &&
            m.clientId == null &&
            m.text == e.text &&
            inWindow) {
          e.matched = true;
          msgs[i] = ChatMessage(
            id: m.id,
            clientId: e.clientId,
            userId: m.userId,
            fromAdmin: m.fromAdmin,
            text: m.text,
            time: m.time,
            status: m.status,
            replyTo: m.replyTo,
          );
          break;
        }
      }
    }
  }

  List<Conversation> _conversations() {
    final byKey = <String, List<Map<String, dynamic>>>{};
    for (final m in _items) {
      byKey.putIfAbsent(_feedbackKey(m), () => []).add(m);
    }
    final list = <Conversation>[];
    byKey.forEach((key, items) {
      final msgs = _messagesFor(key);
      if (msgs.isEmpty) return;
      final last = msgs.last;
      var awaiting = 0;
      for (var i = msgs.length - 1; i >= 0 && !msgs[i].fromAdmin; i--) {
        awaiting++;
      }
      final first = items.first;
      list.add(Conversation(
        userId: key,
        name: _displayName(first),
        phone: (first['user_phone'] ?? first['phone'] ?? '').toString(),
        lastText: last.text,
        lastTime: last.time,
        lastFromAdmin: last.fromAdmin,
        lastStatus: last.fromAdmin ? last.status : MsgStatus.delivered,
        awaiting: awaiting,
      ));
    });
    list.sort((a, b) {
      if ((a.awaiting > 0) != (b.awaiting > 0)) return a.awaiting > 0 ? -1 : 1;
      return b.lastTime.compareTo(a.lastTime);
    });
    return list;
  }

  // ---- Write operations ----------------------------------------------------

  @override
  Future<void> sendReply({
    required String userId,
    required String text,
    required String clientId,
    String? replyToMessageId,
  }) async {
    // Chagua feedback ya kujibu: ile ya ujumbe unaoujibu (quote), la sivyo
    // ile ya mwisho ya mtumiaji huyo ISIVOJIBIWA, la sivyo ya mwisho kabisa.
    String feedbackId;
    final quotedId = replyToMessageId ?? '';
    if (quotedId.endsWith('u') && quotedId.length > 1) {
      feedbackId = quotedId.substring(0, quotedId.length - 1);
    } else {
      final items = _items.where((m) => _feedbackKey(m) == userId).toList()
        ..sort((a, b) =>
            _parseIso(b['created_at']).compareTo(_parseIso(a['created_at'])));
      String? picked;
      for (final m in items) {
        if (_replyText(m).isEmpty) {
          picked = (m['id'] ?? m['_id'] ?? '').toString();
          break;
        }
      }
      picked ??= items.isNotEmpty
          ? (items.first['id'] ?? items.first['_id'] ?? '').toString()
          : '';
      feedbackId = picked;
    }
    if (feedbackId.isEmpty) {
      throw Exception('Hakuna maoni ya kujibu');
    }

    _sent.add(_SentEcho(clientId, userId, text, DateTime.now()));
    try {
      await ApiService().adminReplyFeedback(feedbackId, text);
      await refresh(force: true);
    } catch (_) {
      rethrow; // ChatController inaonyesha "failed" + kitufe cha kujaribu tena
    }
  }

  @override
  Future<void> deleteConversation(String userId) async {
    final ids = [
      for (final m in _items)
        if (_feedbackKey(m) == userId) (m['id'] ?? m['_id'] ?? '').toString(),
    ].where((s) => s.isNotEmpty).toList();
    if (ids.isEmpty) return;
    for (final id in ids) {
      try {
        await ApiService().adminDeleteFeedback(id);
      } catch (e) {
        AppToast.error(friendlyError(e));
        unawaited(refresh(force: true));
        return;
      }
    }
    _sent.removeWhere((e) => e.userId == userId);
    await refresh(force: true);
  }

  @override
  Future<void> markAllSeen() async {
    // Badge ya shell inafutwa na AdminBadgeService baada ya kujibu tu —
    // kitufe hiki ni no-op kwenye backend ya sasa.
  }
}

