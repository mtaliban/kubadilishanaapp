      (false, 'Sawa', days(3)),
      (true, 'ok', days(3)),
    ]);
    return r;
  }

  void _add(String id, String name, String phone,
      List<(bool, String, DateTime)> items) {
    _people[id] = (name: name, phone: phone);
    _msgs[id] = [
      for (final it in items)
        ChatMessage(
          id: 'm${_n++}',
          userId: id,
          fromAdmin: it.$1,
          text: it.$2,
          time: it.$3,
          status: it.$1 ? MsgStatus.read : MsgStatus.delivered,
        ),
    ];
  }

  /// For testing the live updates: pretend the person sent a message.
  void simulateIncoming(String userId, String text) {
    _msgs[userId]!.add(ChatMessage(
      id: 'm${_n++}',
      userId: userId,
      fromAdmin: false,
      text: text,
      time: DateTime.now(),
    ));
    _changed.add(userId);
  }

  List<Conversation> _conversations() {
    final list = <Conversation>[];
    _msgs.forEach((id, msgs) {
      if (msgs.isEmpty) return;
      final last = msgs.last;
      var awaiting = 0;
      for (var i = msgs.length - 1; i >= 0 && !msgs[i].fromAdmin; i--) {
        awaiting++;
      }
      list.add(Conversation(
        userId: id,
        name: _people[id]!.name,
        phone: _people[id]!.phone,
        lastText: last.text,
        lastTime: last.time,
        lastFromAdmin: last.fromAdmin,
        lastStatus: last.status,
        awaiting: awaiting,
      ));
    });
    list.sort((a, b) {
      if ((a.awaiting > 0) != (b.awaiting > 0)) return a.awaiting > 0 ? -1 : 1;
      return b.lastTime.compareTo(a.lastTime);
    });
    return list;
  }

  @override
  Stream<List<Conversation>> watchConversations() async* {
    yield _conversations();
    yield* _changed.stream.map((_) => _conversations());
  }

  @override
  Stream<List<ChatMessage>> watchMessages(String userId) async* {
    yield List.of(_msgs[userId] ?? const []);
    yield* _changed.stream
        .where((id) => id == userId)
        .map((_) => List.of(_msgs[userId] ?? const []));
  }

  @override
  Future<void> sendReply({
    required String userId,
    required String text,
    required String clientId,
    String? replyToMessageId,
  }) async {
    await Future<void>.delayed(const Duration(milliseconds: 400));
    final list = _msgs[userId]!;
    ReplyRef? ref;
    if (replyToMessageId != null) {
      final target = list.where((m) => m.id == replyToMessageId);
      if (target.isNotEmpty) {
        final t = target.first;
        ref = ReplyRef(t.id, t.fromAdmin ? 'Wewe' : _people[userId]!.name, t.text);
      }
    }
    // The saved message echoes the clientId -> the app replaces its local copy.
    list.add(ChatMessage(
      id: 'm${_n++}',
      clientId: clientId,
      userId: userId,
      fromAdmin: true,
      text: text,
      time: DateTime.now(),
      status: MsgStatus.delivered,
      replyTo: ref,
    ));
    _changed.add(userId);
  }

  @override
  Future<void> deleteConversation(String userId) async {
    _msgs.remove(userId);
    _people.remove(userId);
    _changed.add(userId);
  }

  @override
  Future<void> markAllSeen() async {}
}

