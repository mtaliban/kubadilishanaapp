class _MaoniChatPageState extends State<MaoniChatPage> {
  late final ChatController _ctrl;
  final _scroll = ScrollController();
  final _input = TextEditingController();
  final _focus = FocusNode();
  int _lastCount = 0;
  bool _lastWasMine = false;

  @override
  void initState() {
    super.initState();
    _ctrl = ChatController(
      repo: widget.repo,
      userId: widget.conversation.userId,
      userName: widget.conversation.name,
    )..addListener(_onChanged);
    _scroll.addListener(() {
      // list is reversed: offset 0 = newest message at the bottom
      _ctrl.setAtBottom(_scroll.hasClients && _scroll.offset < 80);
    });
    _input.addListener(() => setState(() {}));
  }

  void _onChanged() {
    // The list is reversed (newest at offset 0). When the user is already at
    // the bottom, a new incoming message simply appears there and stays
    // visible. When the user scrolled up, we do NOT yank the view: a
    // "new messages" button appears instead (see ChatController.newWhileAway).
    if (mounted) setState(() {});
  }

  void _scrollToBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_scroll.hasClients) {
        _scroll.animateTo(0,
            duration: const Duration(milliseconds: 250),
            curve: Curves.easeOut);
      }
    });
  }

  void _send() {
    if (_ctrl.send(_input.text)) {
      _input.clear();
      _scrollToBottom();
    }
  }

  @override
  void dispose() {
    _ctrl.removeListener(_onChanged);
    _ctrl.dispose();
    _scroll.dispose();
    _input.dispose();
    _focus.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final c = widget.conversation;
    final entries = _entries(_ctrl.messages);
    final hasText = _input.text.trim().isNotEmpty;

    return Scaffold(
      backgroundColor: Colors.white,
      body: SafeArea(
        child: Column(
          children: [
            _topBar(c),
            Expanded(
              child: Stack(
                children: [
                  ListView.builder(
                    controller: _scroll,
                    reverse: true,
                    padding: const EdgeInsets.fromLTRB(12, 6, 12, 12),
                    itemCount: entries.length,
                    itemBuilder: (_, i) =>
                        _entryWidget(entries[entries.length - 1 - i], c),
                  ),
                  if (!_ctrl.atBottom)
                    Positioned(
                      right: 14,
                      bottom: 12,
                      child: _Press(
                        onTap: _scrollToBottom,
                        child: Stack(
                          clipBehavior: Clip.none,
                          children: [
                            Container(
                              width: 44,
                              height: 44,
                              decoration: BoxDecoration(
                                color: Colors.white,
                                shape: BoxShape.circle,
                                border: Border.all(color: _C.border),
                                boxShadow: const [
                                  BoxShadow(
                                      color: Color(0x1A141A26),
                                      blurRadius: 8,
                                      offset: Offset(0, 2))
                                ],
                              ),
                              child: const Icon(TablerIcons.chevron_down,
                                  size: 22, color: _C.ink),
                            ),
                            if (_ctrl.newWhileAway > 0)
                              Positioned(
                                top: -6,
                                right: -4,
                                child: _CountBadge(_ctrl.newWhileAway,
                                    border: true),
                              ),
                          ],
                        ),
                      ),
                    ),
                ],
              ),
            ),
            if (_ctrl.replyTo != null) _replyPreview(c),
            _inputBar(hasText),
          ],
        ),
      ),
    );
