String _initial(String name) =>
    name.trim().isEmpty ? '?' : name.trim()[0].toUpperCase();

String _firstName(String name) {
  final f = name.trim().split(RegExp(r'\s+')).first;
  if (f.isEmpty) return name;
  return f[0].toUpperCase() + f.substring(1).toLowerCase();
}

String _two(int n) => n.toString().padLeft(2, '0');
String _hm(DateTime t) => '${_two(t.hour)}:${_two(t.minute)}';

const _weekdays = [
  'Jumatatu', 'Jumanne', 'Jumatano', 'Alhamisi', 'Ijumaa', 'Jumamosi', 'Jumapili'
];
const _months = [
  'Jan', 'Feb', 'Mac', 'Apr', 'Mei', 'Jun', 'Jul', 'Ago', 'Sep', 'Okt', 'Nov', 'Des'
];

int _daysAgo(DateTime t) {
  final now = DateTime.now();
  final a = DateTime(now.year, now.month, now.day);
  final b = DateTime(t.year, t.month, t.day);
  return a.difference(b).inDays;
}

/// Inbox row time: today -> HH:mm, yesterday -> Jana, this week -> weekday.
String _listTime(DateTime t) {
  final d = _daysAgo(t);
  if (d <= 0) return _hm(t);
  if (d == 1) return 'Jana';
  if (d < 7) return _weekdays[t.weekday - 1];
  return '${_two(t.day)}/${_two(t.month)}/${t.year}';
}

/// Chat day chip: Leo / Jana / 12 Okt 2026.
String _dayLabel(DateTime d) {
  final n = _daysAgo(d);
  if (n <= 0) return 'Leo';
  if (n == 1) return 'Jana';
  return '${d.day} ${_months[d.month - 1]} ${d.year}';
}

