class _SwipeToReply extends StatefulWidget {
  final Widget child;
  final VoidCallback onReply;
  const _SwipeToReply({required this.child, required this.onReply});

  @override
  State<_SwipeToReply> createState() => _SwipeToReplyState();
}

class _SwipeToReplyState extends State<_SwipeToReply>
    with SingleTickerProviderStateMixin {
  static const _max = 84.0;
  static const _trigger = 60.0;

  double _dx = 0;
  double _from = 0;
  bool _fired = false;
  // AnimationController inaundwa kwenye initState (SIYO late field) —
  // kuunda ticker wakati wa dispose (late field isiyowahi kutumika) kunasoma
  // ancestor ya widget iliyo-deactivated —Flutter inakataza (debug assertion).
  late final AnimationController _back;

  @override
  void initState() {
    super.initState();
    _back = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 200),
    )..addListener(() {
        setState(
            () => _dx = _from * (1 - Curves.easeOut.transform(_back.value)));
      });
  }

  @override
  void dispose() {
    _back.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final p = (_dx / _trigger).clamp(0.0, 1.0);
    return GestureDetector(
      behavior: HitTestBehavior.translucent,
      onHorizontalDragStart: (_) => _back.stop(),
      onHorizontalDragUpdate: (d) {
        setState(() => _dx = (_dx + d.delta.dx).clamp(0.0, _max));
        if (_dx >= _trigger && !_fired) {
          _fired = true;
          HapticFeedback.lightImpact();
        }
      },
      onHorizontalDragEnd: (_) {
        if (_fired) widget.onReply();
        _fired = false;
        _from = _dx;
        _back.forward(from: 0);
      },
      child: SizedBox(
        width: double.infinity,
        child: Stack(
          children: [
            Positioned(
              left: 4,
              top: 0,
              bottom: 0,
              child: Center(
                child: Opacity(
                  opacity: p,
                  child: Transform.scale(
                    scale: .6 + p * .4,
                    child: Container(
                      width: 32,
                      height: 32,
                      decoration: const BoxDecoration(
                          color: _C.replyIconBg, shape: BoxShape.circle),
                      child: const Icon(TablerIcons.arrow_back_up,
                          size: 18, color: _C.chipText),
                    ),
                  ),
                ),
              ),
            ),
            Transform.translate(offset: Offset(_dx, 0), child: widget.child),
          ],
        ),
      ),
    );
  }
}

