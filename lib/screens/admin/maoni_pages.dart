enum MsgStatus { sending, sent, delivered, read, failed }

class ReplyRef {
  final String messageId;
  final String senderName;
  final String text;
  const ReplyRef(this.messageId, this.senderName, this.text);
}

class ChatMessage {
  /// Server id. For a message that is still being sent this may be a temporary
  /// value; the real message from the backend replaces it (matched by clientId).
  final String id;

  /// Id generated by the app when sending. The backend MUST echo it back so the
  /// app can replace the local copy instead of showing the message twice.
  final String? clientId;
  final String userId;
  final bool fromAdmin;
  final String text;
  final DateTime time;
  final MsgStatus status;
  final ReplyRef? replyTo;

  const ChatMessage({
    required this.id,
    this.clientId,
    required this.userId,
    required this.fromAdmin,
    required this.text,
    required this.time,
    this.status = MsgStatus.sent,
    this.replyTo,
  });

  ChatMessage copyWith({MsgStatus? status}) => ChatMessage(
        id: id,
        clientId: clientId,
        userId: userId,
        fromAdmin: fromAdmin,
        text: text,
        time: time,
        status: status ?? this.status,
        replyTo: replyTo,
      );
}

/// ONE row per person in the inbox.
class Conversation {
  final String userId;
  final String name;
  final String phone;
  final String lastText;
  final DateTime lastTime;
  final bool lastFromAdmin;
  final MsgStatus lastStatus;

  /// Number of messages from this person after the admin's last reply.
  /// 0 = nothing waiting. Replying clears it (opening the chat does NOT).
  final int awaiting;

  const Conversation({
    required this.userId,
    required this.name,
    required this.phone,
    required this.lastText,
    required this.lastTime,
    required this.lastFromAdmin,
    this.lastStatus = MsgStatus.delivered,
    this.awaiting = 0,
  });
}

// ----------------------------------------------------------------------------
// Repository: connect THIS to your backend (REST + websocket / Firestore / ...)
// ----------------------------------------------------------------------------
abstract class MaoniRepository {
  /// Live list of conversations, ONE per person, newest first.
  Stream<List<Conversation>> watchConversations();

  /// Live list of ALL messages with one person, oldest first. Must emit the
  /// current list immediately and again whenever anything changes (new
  /// incoming message, your reply confirmed, status changed).
  Stream<List<ChatMessage>> watchMessages(String userId);

  /// Send an admin reply. The backend must store it once and echo [clientId]
  /// on the saved message (so the app can match it).
  Future<void> sendReply({
    required String userId,
    required String text,
    required String clientId,
    String? replyToMessageId,
  });

  Future<void> deleteConversation(String userId);

  /// Optional: header button "mark all seen". Does not change `awaiting`.
  Future<void> markAllSeen();
}

