// Chat controller: merges server messages + pending local ones WITHOUT dupes
// ----------------------------------------------------------------------------
class ChatController extends ChangeNotifier {
  final MaoniRepository repo;
  final String userId;
  final String userName;

  List<ChatMessage> _server = const [];
  final List<ChatMessage> _pending = [];
  StreamSubscription<List<ChatMessage>>? _sub;
  ChatMessage? replyTo;
  bool atBottom = true;
  int newWhileAway = 0;
  bool loaded = false;

  ChatController({
    required this.repo,
    required this.userId,
    required this.userName,
  }) {
    _sub = repo.watchMessages(userId).listen(_onServer);
  }

  /// Final list shown on screen (oldest first). A pending local message is
  /// hidden as soon as the backend echo with the same clientId arrives.
  List<ChatMessage> get messages {
    final echoed = <String>{
      for (final m in _server)
        if (m.clientId != null) m.clientId!,
    };
    final seenIds = <String>{};
    final out = <ChatMessage>[];
    for (final m in _server) {
      if (seenIds.add(m.id)) out.add(m); // never show the same id twice
    }
    for (final p in _pending) {
      if (!echoed.contains(p.clientId)) out.add(p);
    }
    out.sort((a, b) => a.time.compareTo(b.time));
    return out;
  }

  void _onServer(List<ChatMessage> list) {
    final prevIncoming = _server.where((m) => !m.fromAdmin).length;
    final nowIncoming = list.where((m) => !m.fromAdmin).length;
    _server = list;
    final echoed = {
      for (final m in list)
        if (m.clientId != null) m.clientId!,
    };
    _pending.removeWhere((p) => p.status != MsgStatus.failed && echoed.contains(p.clientId));
    if (loaded && nowIncoming > prevIncoming && !atBottom) {
      newWhileAway += nowIncoming - prevIncoming;
    }
    loaded = true;
    notifyListeners();
  }

  void setReply(ChatMessage? m) {
    replyTo = m;
    notifyListeners();
  }

  void setAtBottom(bool v) {
    if (atBottom == v) return;
    atBottom = v;
    if (v) newWhileAway = 0;
    notifyListeners();
  }

  /// Returns true if a message was started.
  bool send(String raw) {
    final text = raw.trim();
    if (text.isEmpty) return false;
    final clientId =
        '${DateTime.now().microsecondsSinceEpoch}-${math.Random().nextInt(1 << 20)}';
    final ref = replyTo == null
        ? null
        : ReplyRef(replyTo!.id, replyTo!.fromAdmin ? 'Wewe' : userName,
            replyTo!.text);
    final local = ChatMessage(
      id: 'local-$clientId',
      clientId: clientId,
      userId: userId,
      fromAdmin: true,
      text: text,
      time: DateTime.now(),
      status: MsgStatus.sending,
      replyTo: ref,
    );
    _pending.add(local);
    final replyId = replyTo?.id;
    replyTo = null;
    notifyListeners();
    _dispatch(local, replyId);
    return true;
  }

  Future<void> _dispatch(ChatMessage local, String? replyId) async {
    try {
      await repo.sendReply(
        userId: userId,
        text: local.text,
        clientId: local.clientId!,
        replyToMessageId: replyId,
      );
    } catch (_) {
      final i = _pending.indexWhere((p) => p.clientId == local.clientId);
      if (i >= 0) {
        _pending[i] = _pending[i].copyWith(status: MsgStatus.failed);
        notifyListeners();
      }
    }
  }

  void retry(ChatMessage failed) {
    final i = _pending.indexWhere((p) => p.clientId == failed.clientId);
    if (i < 0) return;
    _pending[i] = _pending[i].copyWith(status: MsgStatus.sending);
    notifyListeners();
    _dispatch(_pending[i], failed.replyTo?.messageId);
  }

  @override
  void dispose() {
    _sub?.cancel();
    super.dispose();
  }
}

